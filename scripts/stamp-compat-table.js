#!/usr/bin/env node
'use strict';
// Writes the generated compatibility table between the compat-table markers in README.md and
// the docs guide. Usage: node scripts/stamp-compat-table.js [--check]
// --check exits 1 when a file differs from a fresh build and writes nothing.

const fs = require('node:fs');
const path = require('node:path');
const { buildCompatRows, renderCompatMarkdown, MARKERS } = require('./lib/compat-table');

const root = path.join(__dirname, '..');
const FILES = [
  ['README.md', MARKERS.md],
  ['docs/site/content/docs/guides/orchestkit-on-pi-codex-cursor.mdx', MARKERS.mdx],
];
const check = process.argv.includes('--check');
const rows = buildCompatRows(root);
const table = renderCompatMarkdown(rows);
let drift = 0;

// The site's table component reads the same rows. issues stays null ("?") for every host until a
// host's labelling pass is recorded and counted (approved mockup, Yonatan 16.11.2026: "? not 0").
const dataFile = path.join(root, 'docs/site/lib/generated/compat-data.ts');
const dataText = [
  '// GENERATED by scripts/stamp-compat-table.js from the pack manifests. Do not edit.',
  'export type CompatRow = { id: string; name: string; skills: number | null; agents: number | null;',
  '  roles: number | null; hooks: number | "not yet" | null; hooksIssue: number | null; route: string; minVersion: string | null; issues: number | null };',
  `export const COMPAT_ROWS: CompatRow[] = ${JSON.stringify(rows.map((r) => ({ ...r, issues: null })), null, 2)};`,
  '',
].join('\n');
const oldData = fs.existsSync(dataFile) ? fs.readFileSync(dataFile, 'utf8') : '';
if (oldData !== dataText) {
  drift += 1;
  if (check) console.error('stamp-compat-table: docs/site/lib/generated/compat-data.ts is out of date');
  else fs.writeFileSync(dataFile, dataText);
}

for (const [rel, [start, end]] of FILES) {
  const file = path.join(root, rel);
  const text = fs.readFileSync(file, 'utf8');
  const a = text.indexOf(start);
  const b = text.indexOf(end, a + start.length);
  if (a < 0 || b < 0) {
    console.error(`stamp-compat-table: no markers in ${rel}`);
    process.exit(1);
  }
  const next = `${text.slice(0, a + start.length)}\n\n${table}\n\n${text.slice(b)}`;
  if (next === text) continue;
  drift += 1;
  if (check) console.error(`stamp-compat-table: ${rel} is out of date`);
  else fs.writeFileSync(file, next);
}

if (check && drift) process.exit(1);
console.log(check ? 'stamp-compat-table: up to date' : `stamp-compat-table: ${drift} file(s) updated`);
