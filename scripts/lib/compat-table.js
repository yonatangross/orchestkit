'use strict';
// ============================================================================
// The compatibility table: one row per host, every number read, never typed
// ============================================================================
// Sources:
//   hosts, order, names   docs/site/lib/host-installs.ts (HOST_INSTALLS)
//   per-host sets         scripts/lib/library-hosts.js (the pack manifests)
//   Claude Code skills    plugins/ork/skills, plus plugins/ork-extras/skills as extraSkills
//   Claude Code agents    plugins/ork/agents/*.md
//   Claude Code hooks     the README's stamped ork:hooks marker (bin/count-hooks.sh via stamp-counts.sh)
//   minimum version       shared/cc-support.json supported_floor (Claude Code only)
// An unknown number is null and renders "?", never 0. scripts/stamp-compat-table.js writes the
// rendered table between the markers below; tests/unit/test-compat-table.mjs fails on drift.

const fs = require('node:fs');
const path = require('node:path');
const { buildLibraryHosts } = require('./library-hosts');

const MARKERS = {
  md: ['<!-- compat-table:start (generated by scripts/stamp-compat-table.js) -->', '<!-- compat-table:end -->'],
  mdx: ['{/* compat-table:start (generated by scripts/stamp-compat-table.js) */}', '{/* compat-table:end */}'],
};

// How each host installs it: a word or two, not a number, so it is kept here beside the ids.
const ROUTE = {
  claude: 'plugin (CLI)',
  cursor: 'plugin (Settings)',
  codex: 'ork-codex pack',
  devin: 'plugin (git)',
  opencode: 'skills.sh',
  muse: 'plugin (muse)',
  pi: 'pi manifest',
  agy: 'plugin (claude-code)',
};

function hostOrder(root) {
  const site = fs.readFileSync(path.join(root, 'docs/site/lib/host-installs.ts'), 'utf8');
  const start = site.indexOf('export const HOST_INSTALLS');
  const block = site.slice(start, site.indexOf('\n];', start));
  const ids = [...block.matchAll(/^\t\tid: "([a-z]+)",$/gm)].map((m) => m[1]);
  const names = [...block.matchAll(/^\t\tname: "([^"]+)",$/gm)].map((m) => m[1]);
  return ids.map((id, i) => ({ id, name: names[i] }));
}

function countDirs(dir) {
  try {
    return fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('.')).length;
  } catch {
    return null;
  }
}

function countFiles(dir, ext) {
  try {
    return fs.readdirSync(dir).filter((n) => n.endsWith(ext)).length;
  } catch {
    return null;
  }
}

function stampedHooks(root) {
  try {
    const m = fs.readFileSync(path.join(root, 'README.md'), 'utf8').match(/<!--ork:hooks-->(\d+)<!--\/ork-->/);
    return m ? Number(m[1]) : null;
  } catch {
    return null;
  }
}

function ccFloor(root) {
  try {
    return JSON.parse(fs.readFileSync(path.join(root, 'shared/cc-support.json'), 'utf8')).supported_floor || null;
  } catch {
    return null;
  }
}

const size = (set) => (Array.isArray(set) ? set.length : null);

// A cell says "none" only where a host was positively measured and nothing registers.
// Measured 2026-11-22 (docs/audits/host-support-2026-11-22.md): `muse plugins inspect ork`
// shows capabilities.hooks: [] and no agents capability at all; `agy plugin list` lists no
// hooks component for ork (hq-ext shows its 8, so agy does count them); opencode's agent and
// plugin-hook surfaces take its own formats and the pack ships none. Hooks that a tracked
// issue will bring are "not yet" with the issue number (approved mockup); every other number
// no manifest gives is null ("?"). Outside looks review 16.11: "none" read as a measured zero.
const HOOKS_NOT_YET = { cursor: 4004, codex: 4004, pi: 4004 };
const HOOKS_MEASURED_NONE = new Set(['muse', 'agy', 'opencode']);
const AGENTS_MEASURED_NONE = new Set(['muse', 'opencode']);
// Agents: Cursor's marketplace (ork, ork-extras), Codex's roles, Devin's and Antigravity's
// claude-code plugin import all come from a pack. Devin is read in its own branch below.
const AGENTS_READ = new Set(['cursor', 'codex', 'agy']);

// The lifecycle events a devin session fires, from its config schema (~/.config/devin/config.json),
// measured on devin 3000.14.30821. Entries on other events are never invoked.
const DEVIN_HOOK_EVENTS = new Set([
  'Notification', 'PermissionRequest', 'PostToolUse', 'PreToolUse',
  'SessionEnd', 'SessionStart', 'Stop', 'SubagentStop', 'UserPromptSubmit',
]);

// "58 of 103": the hooks.json entries that land on Devin's supported events, read live.
function devinHooks(root) {
  try {
    const hooks = JSON.parse(
      fs.readFileSync(path.join(root, 'plugins/ork/hooks/hooks.json'), 'utf8'),
    ).hooks;
    let total = 0;
    let supported = 0;
    for (const [event, groups] of Object.entries(hooks)) {
      const n = groups.reduce((acc, g) => acc + (Array.isArray(g.hooks) ? g.hooks.length : 0), 0);
      total += n;
      if (DEVIN_HOOK_EVENTS.has(event)) supported += n;
    }
    return total ? `${supported} of ${total}` : null;
  } catch {
    return null;
  }
}

function skillNames(dir) {
  try {
    return fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('.')).map((e) => e.name);
  } catch {
    return [];
  }
}

// skills is what the host's core install gives; extraSkills is what the opt-in ork-extras plugin
// adds on top (null where the host has no ork-extras), so a core install is never shown the total.
function buildCompatRows(root) {
  const sets = buildLibraryHosts(root);
  const extrasNames = new Set(skillNames(path.join(root, 'plugins/ork-extras/skills')));
  return hostOrder(root).map(({ id, name }) => {
    const s = sets[id] || { skills: null, agents: null, hooks: 'unknown' };
    const row = { id, name, route: ROUTE[id] || '?', minVersion: null, roles: null, hooksIssue: null, extraSkills: null };
    if (id === 'claude') {
      row.skills = countDirs(path.join(root, 'plugins/ork/skills'));
      row.extraSkills = extrasNames.size || null;
      row.agents = countFiles(path.join(root, 'plugins/ork/agents'), '.md');
      row.hooks = stampedHooks(root);
      row.minVersion = ccFloor(root);
    } else if (id === 'devin') {
      // .devin-plugin/plugin.json declares the skills folder; agents and hooks are not declared.
      let manifest = null;
      try {
        manifest = JSON.parse(fs.readFileSync(path.join(root, '.devin-plugin/plugin.json'), 'utf8'));
      } catch {
        manifest = null;
      }
      const skillsDir = manifest && typeof manifest.skills === 'string' ? manifest.skills.replace(/^\.\//, '') : null;
      row.skills = skillsDir ? countDirs(path.join(root, skillsDir)) : null;
      row.agents = countFiles(path.join(root, 'plugins/ork/agents'), '.md');
      row.hooks = devinHooks(root);
    } else {
      // Only Cursor installs ork-extras as its own plugin; a skills.sh starter is one install.
      const extra = id === 'cursor' && Array.isArray(s.skills) ? s.skills.filter((n) => extrasNames.has(n)).length : 0;
      row.skills = Array.isArray(s.skills) ? s.skills.length - extra : null;
      row.extraSkills = extra || null;
      row.roles = Array.isArray(s.roles) && s.roles.length ? s.roles.length : null;
      row.agents = AGENTS_READ.has(id) && !row.roles ? size(s.agents) : AGENTS_MEASURED_NONE.has(id) ? 'none' : null;
      row.hooks = HOOKS_NOT_YET[id] ? 'not yet' : HOOKS_MEASURED_NONE.has(id) ? 'none' : null;
      row.hooksIssue = HOOKS_NOT_YET[id] || null;
    }
    return row;
  });
}

function cell(v) {
  if (v === null || v === undefined) return '?';
  return String(v);
}

function skillsCell(r) {
  return r.extraSkills ? `${cell(r.skills)} + ${r.extraSkills} ork-extras` : cell(r.skills);
}

function hooksCell(r) {
  return r.hooks === 'not yet' && r.hooksIssue ? `not yet (#${r.hooksIssue})` : cell(r.hooks);
}

function renderCompatMarkdown(rows) {
  const lines = [
    '| Host | Skills | Agents | Hooks | Install | Needs |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const agents = r.roles ? `${r.roles} roles` : cell(r.agents);
    const needs = r.minVersion ? `${r.name} ${r.minVersion} or newer` : '';
    lines.push(`| ${r.name} | ${skillsCell(r)} | ${agents} | ${hooksCell(r)} | ${r.route} | ${needs} |`);
  }
  lines.push('');
  lines.push('`+ N ork-extras` is the opt-in second plugin, installed on its own. `?` means not measured yet, never zero. `none` is a measured zero: the host was read and the pack registers nothing there. `not yet` means a tracked issue will bring it. Devin hooks are the hooks.json entries that land on the events Devin fires.');
  return lines.join('\n');
}

/** The text between a start and end marker, or null when either is missing. */
function extractBlock(text, [start, end]) {
  const a = text.indexOf(start);
  const b = text.indexOf(end, a + start.length);
  if (a < 0 || b < 0) return null;
  return text.slice(a + start.length, b);
}

module.exports = { buildCompatRows, renderCompatMarkdown, extractBlock, MARKERS };
