#!/usr/bin/env python3
"""Advisory frontmatter gate for src/**/SKILL.md and src/agents/*.md (G1).

Ported from hq-ext-plugin scripts/check-frontmatter.py (#1983 + #1990), itself
ported from yonyon-assistant scripts/validate.py (skill_head and check_agent),
widened from "Agent Skills spec keys only" to "spec keys UNION the keys Claude
Code reads", because OrchestKit ships to Claude Code and those keys change
runtime behaviour. Every allowlist is read from configs/standards.json (the
frontmatter block), so the registry is the single source; nothing is hardcoded
here. Only src/ is judged: plugins/ is generated by npm run build, so a key
there is a build output of the src/ file the gate already read.

What it checks, per file:
  SKILL.md        required name + description; name matches the registry
                  pattern, is at most name_max chars and equals its folder;
                  description at most description_max; compatibility at most
                  compatibility_max; every top-level key is a spec key or a
                  Claude Code skill key; house-only keys (tags, version,
                  author, ...) sit under metadata; metadata is a one-level
                  string map; allowed-tools is a string.
  src/agents/*.md required name + description; name matches the pattern; every
                  top-level key is name, description, metadata or a Claude Code
                  subagent key; house keys sit under metadata; metadata is a
                  one-level string map.

Violation codes are stable strings (for example house-key:tags) so the ratchet
baseline in configs/frontmatter-baseline.json can list them per file. Only a
code that is NOT in the baseline for that file is reported as new. Counts may
only fall: --write-baseline refuses to record a violation the baseline does not
already hold, and --base-baseline compares the PR head baseline to the copy on
the base branch so a PR cannot add debt and raise the baseline in one commit.
The ratchet exists so the legacy house keys (taskTypes, keywords,
examplePrompts, category, and the rest of the ork vocabulary) do not flag
today; only a NEW key added after the baseline reports.

--widening-from BASE compares two registries instead of scanning files: it
fails when the --registry allowlists are looser than BASE (a key newly allowed
at top level, a required key dropped, name_equals_folder turned off, a limit
raised, name_pattern changed, a house key dropped). A PR therefore cannot erase
its own violations by editing configs/standards.json in the same commit.

Under pull_request_target the workflow runs THIS file from the default branch
and reads the PR head only as data (--root head, never executed). A symlinked
SKILL.md or agents/*.md is refused, so head data cannot point the reader at a
file outside its own tree.

Exit codes:
  0  no new violations
  1  new violations, the baseline grew versus --base-baseline, or the
     allowlists widened versus --widening-from
  2  the gate could not run (registry or baseline unreadable, git failed,
     symlinked input)

Standard library only, portable to python 3.12 (the CI system interpreter).
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "configs" / "standards.json"
BASELINE = ROOT / "configs" / "frontmatter-baseline.json"

EXIT_OK, EXIT_NEW, EXIT_ERROR = 0, 1, 2

# OrchestKit: sources live in src/ (plugins/ is generated by npm run build, so
# gating it too would count every file twice). src/agents/*.md is the agent
# set minus the documentation files below; every SKILL.md under src/ counts,
# which covers src/skills/*/SKILL.md and src/codex/ork-codex/skills/*/SKILL.md.
AGENT_PATH = re.compile(r"^src/agents/[^/]+\.md$")
AGENT_SKIP = frozenset({"src/agents/README.md"})
TOP_LINE = re.compile(r"^([^\s:#][^:]*):(?:[ \t]+(.*))?$")
META_CHILD = re.compile(r"^(\s+)([A-Za-z0-9_.-]+):(?:[ \t]+(.*))?$")
# YAML 1.1/1.2 plain scalars that do NOT load as a string.
NON_STRING_PLAIN = re.compile(
    r"^(?:~|null|Null|NULL|true|True|TRUE|false|False|FALSE|yes|Yes|YES|no|No|NO|on|On|ON|off|Off|OFF"
    r"|[-+]?(?:0|[1-9][0-9_]*)(?:\.[0-9_]*)?(?:[eE][-+]?[0-9]+)?|[-+]?\.[0-9_]+(?:[eE][-+]?[0-9]+)?"
    r"|0o?[0-7_]+|0x[0-9a-fA-F_]+|[-+]?\.(?:inf|Inf|INF)|\.(?:nan|NaN|NAN))$"
)


class GateError(Exception):
    """The gate cannot produce a trustworthy answer (exit 2, never a pass)."""


@dataclass
class Kind:
    required: list[str]
    allowed: set[str]
    name_equals_folder: bool


@dataclass
class Rules:
    name_pattern: re.Pattern[str]
    name_max: int
    description_max: int
    compatibility_max: int
    house_keys: set[str]
    skill: Kind
    agent: Kind


@dataclass
class TopKey:
    key: str
    raw: str
    lineno: int
    children: list[str] = field(default_factory=list)


def load_rules(path: Path = REGISTRY) -> Rules:
    try:
        registry = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise GateError(
            f"cannot load allowlists from {path}: {type(exc).__name__}: {exc}"
        ) from exc
    return rules_from_registry(registry, str(path))


def rules_from_registry(registry: dict, source: str) -> Rules:
    try:
        fm = registry["frontmatter"]
        spec_keys = set(fm["spec_keys"])

        def kind(block: dict) -> Kind:
            base = block["base_keys"]
            base_set = spec_keys if base == "spec_keys" else set(base)
            cc = {entry["key"] for entry in block["claude_code_keys"]}
            return Kind(
                list(block["required"]),
                base_set | cc,
                bool(block["name_equals_folder"]),
            )

        rules = Rules(
            name_pattern=re.compile(fm["name_pattern"]),
            name_max=int(fm["limits"]["name_max"]),
            description_max=int(fm["limits"]["description_max"]),
            compatibility_max=int(fm["limits"]["compatibility_max"]),
            house_keys=set(fm["house_keys"]),
            skill=kind(fm["skill"]),
            agent=kind(fm["agent"]),
        )
    except (ValueError, KeyError, TypeError, re.error) as exc:
        raise GateError(
            f"cannot load allowlists from {source}: {type(exc).__name__}: {exc}"
        ) from exc
    overlap = rules.house_keys & (rules.skill.allowed | rules.agent.allowed)
    if overlap:
        raise GateError(
            f"registry lists {sorted(overlap)} as both house-only and allowed top-level"
        )
    return rules


def parse_frontmatter(text: str) -> tuple[list[TopKey] | None, list[str]]:
    """Split YAML frontmatter into top-level keys with their indented children.

    A deliberately small reader (the gate is stdlib only): it needs top-level
    key names, scalar values and the shape of the metadata block, not a full
    YAML model. Returns (None, []) when the file has no frontmatter.
    """
    lines = text.splitlines()
    if not lines or lines[0].rstrip() != "---":
        return None, []
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].rstrip() == "---")
    except StopIteration:
        return None, []
    keys: list[TopKey] = []
    problems: list[str] = []
    for lineno, line in enumerate(lines[1:end], start=2):
        if not line.strip():
            continue
        if line[0] in " \t":
            if keys:
                keys[-1].children.append(line)
            else:
                problems.append("malformed-line")
            continue
        if line.startswith("#"):
            continue
        match = TOP_LINE.match(line)
        if not match:
            problems.append("malformed-line")
            continue
        keys.append(
            TopKey(match.group(1).strip(), (match.group(2) or "").strip(), lineno)
        )
    return keys, problems


def unquote(raw: str) -> str:
    if raw.startswith('"'):
        try:
            return str(json.loads(raw))
        except ValueError:
            return raw.strip('"')
    if raw.startswith("'") and raw.endswith("'") and len(raw) >= 2:
        return raw[1:-1].replace("''", "'")
    return raw


def is_list(entry: TopKey) -> bool:
    if entry.raw.startswith("["):
        return True
    return not entry.raw and any(
        c.strip().startswith("- ") or c.strip() == "-" for c in entry.children
    )


def scalar(entry: TopKey) -> str:
    """Best-effort string value of a scalar key (block, quoted or plain)."""
    body = [c.strip() for c in entry.children if c.strip()]
    if entry.raw[:1] in ("|", ">"):
        return " ".join(body)
    if entry.raw[:1] in ('"', "'"):
        return unquote(" ".join([entry.raw, *body]) if body else entry.raw)
    return " ".join([entry.raw, *body]).strip()


def registry_widening(base: Rules, head: Rules) -> list[str]:
    """Ways the head allowlists are looser than base. Empty means same or tighter.

    Run from the trusted (default branch) copy of this script with the head
    registry as data. A tightening passes. A changed name_pattern always
    reports, because no script can prove one regex accepts a subset of another.
    A dropped house key is not strictly a loosening, but it recodes every
    house-key:X violation as unknown-key:X and orphans those baseline entries,
    so it needs the same human review.
    """
    out: list[str] = []
    for label in ("skill", "agent"):
        b, h = getattr(base, label), getattr(head, label)
        out += [
            f"{label}: top-level key newly allowed: {k}"
            for k in sorted(h.allowed - b.allowed)
        ]
        out += [
            f"{label}: key no longer required: {k}"
            for k in sorted(set(b.required) - set(h.required))
        ]
        if b.name_equals_folder and not h.name_equals_folder:
            out.append(f"{label}: name_equals_folder turned off")
    for lim in ("name_max", "description_max", "compatibility_max"):
        before, after = getattr(base, lim), getattr(head, lim)
        if after > before:
            out.append(f"limit raised: {lim} {before} -> {after}")
    if head.name_pattern.pattern != base.name_pattern.pattern:
        out.append(
            f"name_pattern changed: {base.name_pattern.pattern!r} -> "
            f"{head.name_pattern.pattern!r} (a regex cannot be proven narrower)"
        )
    out += [
        f"house key dropped (recodes the baseline): {k}"
        for k in sorted(base.house_keys - head.house_keys)
    ]
    return out


def run_widening(args: argparse.Namespace) -> int:
    """--widening-from: fail when --registry is looser than the base registry."""
    base_rules = load_rules(Path(args.widening_from))
    head_rules = load_rules(Path(args.registry))
    found = registry_widening(base_rules, head_rules)
    emit(
        f"allowlist widening: {len(found)} finding(s), {args.registry} versus {args.widening_from}"
    )
    for line in found:
        emit(f"WIDENED {line}")
        if args.github:
            emit(
                f"::error file=configs/standards.json,title=standards allowlist widened::{line}. "
                "A looser allowlist needs the operator's hand merge (eyeball-paths)."
            )
    return EXIT_NEW if found else EXIT_OK


def check_metadata(entry: TopKey) -> list[str]:
    if entry.raw:
        return ["metadata-not-string-map"]
    problems: list[str] = []
    indent: str | None = None
    for child in entry.children:
        stripped = child.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = META_CHILD.match(child)
        if not match:
            problems.append("metadata-not-string-map")
            continue
        this_indent, sub, value = (
            match.group(1),
            match.group(2),
            (match.group(3) or "").strip(),
        )
        if indent is None:
            indent = this_indent
        if this_indent != indent:
            problems.append("metadata-not-string-map")
            continue
        if not value or value[0] in "[{|>&*!":
            problems.append(f"metadata-not-string-map:{sub}")
        elif value[0] not in "\"'" and NON_STRING_PLAIN.match(value):
            problems.append(f"metadata-not-string-map:{sub}")
    return problems


def check_file(relpath: str, text: str, kind_name: str, rules: Rules) -> list[str]:
    kind = rules.skill if kind_name == "skill" else rules.agent
    keys, problems = parse_frontmatter(text)
    if keys is None:
        return ["no-frontmatter"]
    by_key: dict[str, TopKey] = {}
    for entry in keys:
        if entry.key in by_key:
            problems.append(f"duplicate-key:{entry.key}")
        by_key[entry.key] = entry
    for required in kind.required:
        if required not in by_key or not scalar(by_key[required]):
            problems.append(f"missing:{required}")
    if "name" in by_key:
        name = unquote(scalar(by_key["name"]))
        if name and not rules.name_pattern.match(name):
            problems.append("name-charset")
        if len(name) > rules.name_max:
            problems.append("name-too-long")
        if kind.name_equals_folder and name and name != Path(relpath).parent.name:
            problems.append("name-folder-mismatch")
    if (
        "description" in by_key
        and len(scalar(by_key["description"])) > rules.description_max
    ):
        problems.append("description-too-long")
    if (
        "compatibility" in by_key
        and len(scalar(by_key["compatibility"])) > rules.compatibility_max
    ):
        problems.append("compatibility-too-long")
    if "metadata" in by_key:
        problems += check_metadata(by_key["metadata"])
    if (
        kind_name == "skill"
        and "allowed-tools" in by_key
        and is_list(by_key["allowed-tools"])
    ):
        problems.append("allowed-tools-not-string")
    for key in by_key:
        if key in kind.allowed:
            continue
        problems.append(
            f"house-key:{key}" if key in rules.house_keys else f"unknown-key:{key}"
        )
    return sorted(set(problems))


def discover(root: Path) -> list[tuple[str, str]]:
    proc = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=False
    )
    if proc.returncode != 0:
        raise GateError(
            f"git ls-files failed (rc={proc.returncode}): {proc.stderr.decode(errors='replace').strip()}"
        )
    files = [p for p in proc.stdout.decode("utf-8").split("\0") if p]
    found = []
    for path in sorted(files):
        if path in AGENT_SKIP:
            continue
        if path.startswith("src/") and Path(path).name == "SKILL.md":
            found.append((path, "skill"))
        elif AGENT_PATH.match(path):
            found.append((path, "agent"))
    if not found:
        raise GateError(
            "found 0 src/**/SKILL.md or src/agents/*.md files; refusing to report a clean pass"
        )
    return found


def scan(root: Path, rules: Rules) -> dict[str, list[str]]:
    results: dict[str, list[str]] = {}
    for relpath, kind_name in discover(root):
        if (root / relpath).is_symlink():
            raise GateError(
                f"{relpath} is a symlink; the gate reads only regular files in the tree it judges"
            )
        try:
            text = (root / relpath).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise GateError(f"cannot read {relpath}: {exc}") from exc
        # name-equals-folder compares against the file's own folder, so the
        # src/ prefix never reaches it.
        results[relpath] = check_file(relpath, text, kind_name, rules)
    return results


def load_baseline(path: Path) -> dict[str, list[str]]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        files = data["files"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise GateError(
            f"cannot load baseline {path}: {type(exc).__name__}: {exc}"
        ) from exc
    if not isinstance(files, dict) or not all(
        isinstance(v, list) for v in files.values()
    ):
        raise GateError(f"baseline {path}: files must map path to a list of codes")
    return files


def diff(current: dict[str, list[str]], baseline: dict[str, list[str]]):
    new: dict[str, list[str]] = {}
    fixed: dict[str, list[str]] = {}
    for path, codes in current.items():
        extra = sorted(set(codes) - set(baseline.get(path, [])))
        if extra:
            new[path] = extra
    for path, codes in baseline.items():
        gone = sorted(set(codes) - set(current.get(path, [])))
        if gone:
            fixed[path] = gone
    return new, fixed


def base_growth(
    head: dict[str, list[str]], base: dict[str, list[str]]
) -> dict[str, tuple[int, int, list[str]]]:
    """Codes the head baseline holds that the base baseline did not.

    The per-file ratchet alone reads the baseline from the PR head, so a PR
    could add debt and record it in the same commit. This compares the head
    baseline to the one on the base branch: a file whose head codes are not a
    subset of its base codes grew. That covers a raised count and also a swap
    at equal count (one code fixed, a different one added). Lowering passes.
    Returns path -> (base count, head count, added codes).
    """
    grown: dict[str, tuple[int, int, list[str]]] = {}
    for path, codes in sorted(head.items()):
        before = base.get(path, [])
        added = sorted(set(codes) - set(before))
        if added:
            grown[path] = (len(set(before)), len(set(codes)), added)
    return grown


def check_base(
    args: argparse.Namespace, head: dict[str, list[str]], head_label: str
) -> int:
    """Compare the head baseline to the base branch copy (see base_growth)."""
    base_path = Path(args.base_baseline)
    if not base_path.exists():
        emit(
            f"base ratchet: {base_path} is absent (the baseline does not exist on the base branch yet), no floor to compare"
        )
        return 0
    grown = base_growth(head, load_baseline(base_path))
    n_grown = sum(len(added) for _, _, added in grown.values())
    emit(
        f"base ratchet: {len(grown)} file(s), {n_grown} code(s) added to the baseline versus the base branch"
    )
    for path, (n_base, n_head, added) in grown.items():
        emit(f"GROWN {path}: {n_base} -> {n_head} (added {', '.join(added)})")
        if args.github:
            emit(
                f"::error file={head_label},title=frontmatter baseline raised::{path} gained {', '.join(added)}; the baseline may only fall"
            )
    return n_grown


def write_baseline(path: Path, current: dict[str, list[str]]) -> None:
    files = {p: c for p, c in sorted(current.items()) if c}
    payload = {
        "_comment": (
            "Ratchet baseline for scripts/check-frontmatter.py: the frontmatter violations each file carried "
            "when it was recorded. Only codes NOT listed here are reported. Counts may only fall; regenerate "
            "with python3 scripts/check-frontmatter.py --write-baseline after fixing debt (it refuses to add codes)."
        ),
        "total_violations": sum(len(c) for c in files.values()),
        "files_with_violations": len(files),
        "files": files,
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def emit(line: str) -> None:
    sys.stdout.write(line + "\n")


def run(args: argparse.Namespace) -> int:
    rules = load_rules(Path(args.registry))
    root = Path(args.root)
    current = scan(root, rules)
    baseline_path = Path(args.baseline)
    total = sum(len(c) for c in current.values())
    n_skill = sum(1 for p in current if Path(p).name == "SKILL.md")
    n_agent = len(current) - n_skill
    clean = sum(1 for c in current.values() if not c)

    if args.list:
        for path, codes in current.items():
            for code in codes:
                emit(f"{path}: {code}")

    if args.write_baseline:
        if baseline_path.exists():
            new, _ = diff(current, load_baseline(baseline_path))
            if new and not args.allow_new:
                emit(
                    f"REFUSED: {sum(len(c) for c in new.values())} violation(s) are not in the baseline; the ratchet only falls."
                )
                for path, codes in new.items():
                    emit(f"  {path}: {', '.join(codes)}")
                return EXIT_NEW
        write_baseline(baseline_path, current)
        emit(
            f"baseline written: {total} violation(s) in {len(current) - clean} file(s) -> {baseline_path.relative_to(root) if baseline_path.is_relative_to(root) else baseline_path}"
        )
        return EXIT_OK

    baseline = load_baseline(baseline_path)
    new, fixed = diff(current, baseline)
    n_new = sum(len(c) for c in new.values())
    n_fixed = sum(len(c) for c in fixed.values())
    emit(
        f"frontmatter gate: {len(current)} files ({n_skill} SKILL.md, {n_agent} src/agents/*.md), "
        f"{clean} clean, {total} violation(s) now, {total - n_new} baselined, {n_fixed} fixed since baseline, {n_new} NEW"
    )
    for path, codes in new.items():
        for code in codes:
            emit(f"NEW  {path}: {code}")
            if args.github:
                emit(
                    f"::warning file={path},line=1,title=frontmatter gate::{code} (see configs/standards.json frontmatter block)"
                )
    if n_fixed:
        emit(
            f"note: {n_fixed} baselined violation(s) are gone; lower the ratchet with --write-baseline"
        )
    n_grown = 0
    if args.base_baseline:
        head_label = str(
            baseline_path.relative_to(root)
            if baseline_path.is_relative_to(root)
            else baseline_path
        )
        n_grown = check_base(args, baseline, head_label)
    if args.github:
        summary_path = args.step_summary or os.environ.get("GITHUB_STEP_SUMMARY")
        summary = Path(summary_path) if summary_path else None
        if summary:
            with summary.open("a", encoding="utf-8") as fh:
                fh.write("### Frontmatter gate (advisory)\n\n")
                fh.write(
                    "| files | clean | violations now | baselined | fixed | NEW |\n|---|---|---|---|---|---|\n"
                )
                fh.write(
                    f"| {len(current)} | {clean} | {total} | {total - n_new} | {n_fixed} | {n_new} |\n\n"
                )
                for path, codes in new.items():
                    fh.write(f"- `{path}`: {', '.join(codes)}\n")
                if n_grown:
                    fh.write(
                        f"\n**Baseline raised versus the base branch: {n_grown} code(s) added.** The baseline may only fall.\n"
                    )
    return EXIT_NEW if (n_new or n_grown) else EXIT_OK


