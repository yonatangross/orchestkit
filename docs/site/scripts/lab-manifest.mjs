#!/usr/bin/env node
/**
 * lab-manifest.mjs: Lab gallery entries, one fragment file per entry (#4049).
 *
 * Source of truth: docs/site/lab-manifest/<slug>.json, exactly one entry per
 * file, owned by exactly one PR. The old single docs/site/lab-manifest.json
 * was edited by every PR that shipped a playground, so any two concurrent
 * PRs conflicted on it (measured 2026-09-10: five rebase conflicts in one
 * lane, all on that file), and the obvious resolution (--ours / --theirs)
 * silently dropped whichever entry the other side had added while the count
 * still looked right.
 *
 * Generated outputs, committed and diffed by the CI drift gate:
 *   - docs/site/public/lab/<slug>.html   one copy per entry (never conflicts)
 *   - docs/site/lib/generated/lab-data.ts  the aggregate, sorted by slug, ONE
 *     ENTRY PER LINE. Two PRs adding two entries land on two different lines
 *     and git merges them textually. Display order (newest first) belongs to
 *     the gallery component, not to this file: sorting the aggregate by date
 *     would put every same-day addition into the same gap and conflict again.
 *
 * The aggregate is a pure function of the fragments plus the page bytes, so
 * the only correct conflict resolution on lab-data.ts is: take either side,
 * run `npm run build`, commit. Never hand-merge the generated file.
 *
 * `--check` is the read-only set oracle CI runs on every PR head:
 *   - every fragment appears in lab-data.ts and has its public/lab copy;
 *   - lab-data.ts and public/lab/ contain nothing no fragment declares;
 *   - lab-data.ts is byte-identical to a fresh render (a stale regenerate
 *     that dropped an entry fails here even if the count still matches).
 *
 * Usage:
 *   node docs/site/scripts/lab-manifest.mjs            # generate (build step)
 *   node docs/site/scripts/lab-manifest.mjs --check    # verify, write nothing
 *   node docs/site/scripts/lab-manifest.mjs --repo DIR # act on another tree
 *                                                        (tests use fixtures)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const FRAGMENT_DIR = path.join("docs", "site", "lab-manifest");
export const LEGACY_MANIFEST = path.join("docs", "site", "lab-manifest.json");
export const PUBLIC_LAB = path.join("docs", "site", "public", "lab");
export const LAB_DATA = path.join("docs", "site", "lib", "generated", "lab-data.ts");

const SLUG_RE = /^[a-z0-9][a-z0-9-]*$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const KNOWN_KEYS = new Set([
  "slug",
  "source",
  "title",
  "description",
  "tags",
  "date",
  "featured",
  "caseStudy",
]);

const HEADER = `// Generated by docs/site/scripts/lab-manifest.mjs. Do not edit by hand.
// Source of truth: docs/site/lab-manifest/<slug>.json, one fragment per entry.
//
// Sorted by slug, one entry per line, so two PRs adding two entries change two
// different lines and merge textually (#4049). Newest-first display order is
// applied by the gallery at render time, on purpose: sorting here by date would
// put every same-day addition into the same gap and conflict again.
//
// On a merge conflict in this file: take either side, run \`npm run build\`,
// commit. Never resolve the generated file by hand.

export interface LabEntry {
  slug: string;
  title: string;
  description: string;
  tags: string[];
  date: string;
  featured: boolean;
  /** Route of the long-form case study, when one exists */
  caseStudy: string | null;
  sizeKb: number;
}

export const LAB_ENTRIES: LabEntry[] = [
`;
const FOOTER = `];
`;

/** Resolve every path this module touches from one repo root. */
export function resolvePaths(repo) {
  const root = path.resolve(repo);
  return {
    root,
    fragmentDir: path.join(root, FRAGMENT_DIR),
    legacy: path.join(root, LEGACY_MANIFEST),
    publicLab: path.join(root, PUBLIC_LAB),
    labData: path.join(root, LAB_DATA),
  };
}

class ManifestError extends Error {
  constructor(problems) {
    super(problems.join("\n"));
    this.problems = problems;
  }
}

function byteOrder(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

/**
 * Read and validate every fragment. Returns entries sorted by slug. Throws a
 * ManifestError listing every problem at once, so one run reports the whole
 * set rather than the first defect.
 */
export function readFragments(paths) {
  const problems = [];
  if (fs.existsSync(paths.legacy)) {
    problems.push(
      `${LEGACY_MANIFEST} exists. That file was replaced by one fragment per entry under ` +
        `${FRAGMENT_DIR}/<slug>.json (#4049). A rebased branch that still edits it must move its ` +
        `entry into ${FRAGMENT_DIR}/<slug>.json and delete the legacy file.`,
    );
  }
  if (!fs.existsSync(paths.fragmentDir)) {
    problems.push(`${FRAGMENT_DIR}/ is missing; nothing to generate the Lab from.`);
    throw new ManifestError(problems);
  }
  const files = fs
    .readdirSync(paths.fragmentDir)
    .filter((f) => f.endsWith(".json"))
    .sort(byteOrder);
  const entries = [];
  for (const file of files) {
    const rel = path.join(FRAGMENT_DIR, file);
    const stem = file.slice(0, -".json".length);
    if (!SLUG_RE.test(stem)) {
      problems.push(`${rel}: file name must be <slug>.json with a kebab-case slug`);
      continue;
    }
    let raw;
    try {
      raw = JSON.parse(fs.readFileSync(path.join(paths.fragmentDir, file), "utf8"));
    } catch (err) {
      problems.push(`${rel}: not valid JSON (${err.message})`);
      continue;
    }
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
      problems.push(`${rel}: must be a single JSON object (one entry per file)`);
      continue;
    }
    for (const k of Object.keys(raw)) {
      if (!KNOWN_KEYS.has(k)) problems.push(`${rel}: unknown key "${k}"`);
    }
    if (raw.slug !== stem) {
      problems.push(`${rel}: "slug" must equal the file name stem "${stem}" (got ${JSON.stringify(raw.slug)})`);
    }
    if (typeof raw.source !== "string" || !raw.source.endsWith(".html")) {
      problems.push(`${rel}: "source" must be a repo-relative path to an .html file`);
    } else if (path.isAbsolute(raw.source) || raw.source.split(/[\\/]/).includes("..")) {
      problems.push(`${rel}: "source" must stay inside the repo (no absolute path, no "..")`);
    }
    if (typeof raw.date !== "string" || !DATE_RE.test(raw.date)) {
      problems.push(`${rel}: "date" must be YYYY-MM-DD`);
    }
    if (raw.tags !== undefined && !(Array.isArray(raw.tags) && raw.tags.every((t) => typeof t === "string"))) {
      problems.push(`${rel}: "tags" must be an array of strings`);
    }
    for (const k of ["title", "description", "caseStudy"]) {
      if (raw[k] !== undefined && typeof raw[k] !== "string") problems.push(`${rel}: "${k}" must be a string`);
    }
    if (raw.featured !== undefined && typeof raw.featured !== "boolean") {
      problems.push(`${rel}: "featured" must be a boolean`);
    }
    entries.push(raw);
  }
  if (problems.length) throw new ManifestError(problems);
  return entries;
}

/**
 * Resolve the page bytes for one entry. Prefer the repo source; several
 * sources under docs/*.html are gitignored working artifacts, so a clean
 * checkout falls back to the committed public/lab copy. Both missing is a
 * pruned entry: remove the fragment or restore the page.
 */
function readPage(paths, entry, warn) {
  const src = path.join(paths.root, entry.source);
  const committed = path.join(paths.publicLab, `${entry.slug}.html`);
  if (fs.existsSync(src)) return fs.readFileSync(src, "utf8");
  if (fs.existsSync(committed)) {
    warn(`[lab-manifest] source absent (gitignored or pruned): ${entry.source}, keeping committed public/lab/${entry.slug}.html`);
    return fs.readFileSync(committed, "utf8");
  }
  return null;
}

function renderEntry(entry, html) {
  const title = entry.title ?? html.match(/<title>([^<]*)<\/title>/)?.[1]?.trim() ?? entry.slug;
  const description =
    entry.description ?? html.match(/<meta\s+name="description"\s+content="([^"]*)"/)?.[1]?.trim() ?? "";
  return {
    slug: entry.slug,
    title,
    description,
    tags: entry.tags ?? [],
    date: entry.date,
    featured: Boolean(entry.featured),
    caseStudy: entry.caseStudy ?? null,
    sizeKb: Math.round(Buffer.byteLength(html) / 1024),
  };
}

/** The exact text of lab-data.ts for a rendered entry list. */
export function renderLabData(rendered) {
  const lines = [...rendered]
    .sort((a, b) => byteOrder(a.slug, b.slug))
    .map((e) => `  ${JSON.stringify(e)},\n`);
  return HEADER + lines.join("") + FOOTER;
}

/**
 * Compute everything without writing: the rendered entries, the lab-data.ts
 * text, and the page bytes per slug. Shared by generate() and check().
 */
export function render(paths, { warn = console.warn } = {}) {
  const entries = readFragments(paths);
  const rendered = [];
  const pages = new Map();
  const missing = [];
  for (const entry of entries) {
    const html = readPage(paths, entry, warn);
    if (html === null) {
      missing.push(`${entry.source} (fragment ${FRAGMENT_DIR}/${entry.slug}.json)`);
      continue;
    }
    pages.set(entry.slug, html);
    rendered.push(renderEntry(entry, html));
  }
  if (missing.length) {
    throw new ManifestError([
      `missing sources (pruned?): remove the fragment or restore the page:\n  ${missing.join("\n  ")}`,
    ]);
  }
  return { entries, rendered, pages, text: renderLabData(rendered) };
}

/** Write public/lab/<slug>.html for every entry, drop orphans, write lab-data.ts. */
export function generate(paths, opts = {}) {
  const out = render(paths, opts);
  fs.mkdirSync(paths.publicLab, { recursive: true });
  fs.mkdirSync(path.dirname(paths.labData), { recursive: true });
  for (const [slug, html] of out.pages) {
    fs.writeFileSync(path.join(paths.publicLab, `${slug}.html`), html);
  }
  // public/lab is a pure function of the fragments: a copy whose fragment is
  // gone is deleted here, so removing an entry is one file deletion plus a
  // rebuild, and the set check below can treat any orphan as a defect.
  for (const f of fs.readdirSync(paths.publicLab)) {
    if (f.endsWith(".html") && !out.pages.has(f.slice(0, -".html".length))) {
      fs.rmSync(path.join(paths.publicLab, f));
    }
  }
  fs.writeFileSync(paths.labData, out.text);
  return out;
}

/** Slugs declared by the committed lab-data.ts, or null when unreadable. */
export function readCommittedSlugs(labDataPath) {
  if (!fs.existsSync(labDataPath)) return null;
  const text = fs.readFileSync(labDataPath, "utf8");
  const MARKER = "export const LAB_ENTRIES: LabEntry[] = [";
  const start = text.indexOf(MARKER);
  if (start === -1) return null;
  const body = text.slice(start + MARKER.length);
  const end = body.indexOf("\n];");
  if (end === -1) return null;
  const slugs = [];
  for (const line of body.slice(0, end).split("\n")) {
    const trimmed = line.trim().replace(/,$/, "");
    if (!trimmed) continue;
    try {
      const obj = JSON.parse(trimmed);
      if (obj && typeof obj.slug === "string") slugs.push(obj.slug);
    } catch {
      // A multi-line or hand-edited entry is not on the one-per-line contract.
      // The byte comparison in check() reports it; the set here stays partial.
    }
  }
  return slugs;
}

/**
 * Read-only set check. Returns the list of problems (empty means clean).
 * Never writes: safe on a PR head, in CI, and in a dirty working tree.
 */
export function check(paths, opts = {}) {
  let out;
  try {
    out = render(paths, opts);
  } catch (err) {
    if (err instanceof ManifestError) return err.problems;
    throw err;
  }
  const problems = [];
  const declared = new Set(out.rendered.map((e) => e.slug));

  const committed = readCommittedSlugs(paths.labData);
  if (committed === null) {
    problems.push(`${LAB_DATA} is missing or not on the generated contract; run npm run build`);
  } else {
    const inData = new Set(committed);
    for (const slug of declared) {
      if (!inData.has(slug)) problems.push(`${LAB_DATA} lacks "${slug}" (fragment exists); run npm run build`);
    }
    for (const slug of inData) {
      if (!declared.has(slug)) problems.push(`${LAB_DATA} carries "${slug}" but no fragment declares it; run npm run build`);
    }
    const current = fs.readFileSync(paths.labData, "utf8");
    if (current !== out.text) {
      problems.push(`${LAB_DATA} is stale (differs from a fresh render); run npm run build`);
    }
  }

  const published = fs.existsSync(paths.publicLab)
    ? fs.readdirSync(paths.publicLab).filter((f) => f.endsWith(".html")).map((f) => f.slice(0, -".html".length))
    : [];
  const pubSet = new Set(published);
  for (const slug of declared) {
    if (!pubSet.has(slug)) problems.push(`${PUBLIC_LAB}/${slug}.html is missing (fragment exists); run npm run build`);
  }
  for (const slug of published) {
    if (!declared.has(slug)) problems.push(`${PUBLIC_LAB}/${slug}.html has no fragment (orphan); run npm run build`);
  }
  return problems;
}

function cli(argv) {
  let repo = null;
  let mode = "generate";
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") mode = "check";
    else if (a === "--repo") repo = argv[++i];
    else {
      console.error(`[lab-manifest] unknown argument: ${a}`);
      return 2;
    }
  }
  if (!repo) {
    const here = path.dirname(fileURLToPath(import.meta.url));
    repo = path.resolve(here, "..", "..", "..");
  }
  const paths = resolvePaths(repo);
  if (mode === "check") {
    // Read-only and quiet: the source-absent warnings belong to a build, not
    // to a CI gate that only needs the verdict.
    const problems = check(paths, { warn: () => {} });
    if (problems.length) {
      console.error(`[lab-manifest] set check FAILED, ${problems.length} problem(s):`);
      for (const p of problems) console.error(`  - ${p}`);
      return 1;
    }
    const n = readCommittedSlugs(paths.labData)?.length ?? 0;
    console.log(`[lab-manifest] set check OK: ${n} fragment(s) == lab-data.ts == public/lab/`);
    return 0;
  }
  try {
    const out = generate(paths);
    console.log(`[lab-manifest] ${out.rendered.length} lab entries -> public/lab/ + lab-data.ts`);
    return 0;
  } catch (err) {
    if (err instanceof ManifestError) {
      console.error(`[lab-manifest] ${err.problems.length} problem(s):`);
      for (const p of err.problems) console.error(`  - ${p}`);
      return 1;
    }
    throw err;
  }
}

// Main-module guard. Node resolves the ESM URL through symlinks, argv[1] is
// whatever the caller typed, so a bare path.resolve() compare misses on any
// symlinked invocation (macOS /tmp -> /private/tmp): the CLI silently never
// ran and exited 0 with no output, a fail-open oracle (found in review of
// #4064). realpath BOTH sides; an unresolvable argv[1] is not us.
function isMainModule() {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMainModule()) {
  process.exit(cli(process.argv.slice(2)));
}
