#!/usr/bin/env node
/**
 * generate-lab-data.mjs — Lab gallery + CC-adoption board data generator.
 *
 * Reads docs/site/lab-manifest.json (the curated allowlist), copies each
 * source playground HTML into docs/site/public/lab/<slug>.html, and emits:
 *   - lib/generated/lab-data.ts          (gallery entries)
 *   - lib/generated/cc-adoption-data.ts  (from shared/cc-adoption-gaps.json
 *                                         + shared/cc-support.json)
 *
 * Output must be a PURE FUNCTION of tracked inputs. scripts/build-plugins.sh
 * runs this during `npm run build`, and ci.yml diffs lib/generated/ afterwards,
 * so anything that varies per run (HEAD sha, wall-clock date) would fail that
 * gate on every PR rather than only on real drift. See SOURCE_DIGEST below.
 *
 * Convention (matches scripts/generate-docs-data.js): run locally, commit the
 * outputs. Sources under docs/*.html may be gitignored working artifacts —
 * the committed public/lab copies are the published canon.
 *
 * Source resolution: prefer the repo source file; when it is absent (several
 * sources under docs/*.html are gitignored working artifacts, so clean
 * checkouts don't have them) fall back to the committed public/lab copy with
 * a warning. Fails loudly only when BOTH are missing (truly pruned entry):
 * remove the entry or restore the file.
 */
import { createHash } from "node:crypto";
import { mergeWaves } from "./merge-adoption-waves.mjs";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SITE = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const REPO = path.resolve(SITE, "..", "..");
const OUT_LAB = path.join(SITE, "public", "lab");
const GEN = path.join(SITE, "lib", "generated");

const manifest = JSON.parse(fs.readFileSync(path.join(SITE, "lab-manifest.json"), "utf8"));

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');

// ---------- lab entries ----------
fs.mkdirSync(OUT_LAB, { recursive: true });
const entries = [];
const missing = [];
for (const e of manifest.entries) {
  const src = path.join(REPO, e.source);
  const committed = path.join(OUT_LAB, `${e.slug}.html`);
  let html;
  if (fs.existsSync(src)) {
    html = fs.readFileSync(src, "utf8");
  } else if (fs.existsSync(committed)) {
    console.warn(
      `[generate-lab-data] source absent (gitignored or pruned): ${e.source} — keeping committed public/lab/${e.slug}.html`,
    );
    html = fs.readFileSync(committed, "utf8");
  } else {
    missing.push(e.source);
    continue;
  }
  const title = e.title ?? html.match(/<title>([^<]*)<\/title>/)?.[1]?.trim() ?? e.slug;
  const description =
    e.description ??
    html.match(/<meta\s+name="description"\s+content="([^"]*)"/)?.[1]?.trim() ??
    "";
  fs.writeFileSync(path.join(OUT_LAB, `${e.slug}.html`), html);
  entries.push({
    slug: e.slug,
    title,
    description,
    tags: e.tags ?? [],
    date: e.date ?? "",
    featured: Boolean(e.featured),
    caseStudy: e.caseStudy ?? null,
    sizeKb: Math.round(Buffer.byteLength(html) / 1024),
  });
}
if (missing.length) {
  console.error(
    `[generate-lab-data] missing sources (pruned?): remove from lab-manifest.json or restore:\n  ${missing.join("\n  ")}`,
  );
  process.exit(1);
}
entries.sort((a, b) => (a.date < b.date ? 1 : -1));

const labTs = `// Generated by docs/site/scripts/generate-lab-data.mjs — do not edit by hand.
// Source of truth: docs/site/lab-manifest.json

export interface LabEntry {
  slug: string;
  title: string;
  description: string;
  tags: string[];
  date: string;
  featured: boolean;
  /** Route of the long-form case study, when one exists */
  caseStudy: string | null;
  sizeKb: number;
}

export const LAB_ENTRIES: LabEntry[] = ${JSON.stringify(entries, null, 2)};
`;
fs.writeFileSync(path.join(GEN, "lab-data.ts"), labTs);

// ---------- cc-adoption board ----------
const gapsRaw = fs.readFileSync(path.join(REPO, "shared", "cc-adoption-gaps.json"), "utf8");
const supportRaw = fs.readFileSync(path.join(REPO, "shared", "cc-support.json"), "utf8");
const gaps = JSON.parse(gapsRaw);
const support = JSON.parse(supportRaw);

// Provenance stamp over the SOURCE BYTES, deliberately not `git rev-parse HEAD`
// plus today's date. This output is committed and CI re-runs the build then
// diffs it, so a per-run stamp turns the drift gate into a false alarm on every
// PR. A digest moves when, and only when, the two source files move.
// Still a digest of the two SOURCE files, not of the merged output: the merge
// is idempotent for an unchanged checkout, so a rebuild in CI reproduces the
// same bytes and the drift gate stays quiet.
const sourceDigest = createHash("sha256").update(gapsRaw).update(supportRaw).digest("hex").slice(0, 12);

// shared/cc-adoption-gaps.json is a TRANSIENT WORK QUEUE, not a history.
// cc-release-watch.mjs rewrites it every run and deliberately prunes entries the
// filer has already stamped `issues_filed_at`, so the file stays bounded. The
// board was generated from it by replacement, which made a published history
// track a shrinking queue: measured 2026-08-21, 18 waves on main against 2 at
// the nightly PR's head. Regenerating there would have published a 2-wave board
// and dropped 16 waves of adoption history, and because the drift gate compares
// a fresh build against the committed file, the snapshot PR arrived permanently
// red (#3645, blocking #3644).
//
// The queue now only ever ADDS. We merge the freshly-derived waves over whatever
// the committed board already holds, keyed by version, so a prune can never
// delete a published wave. Deriving instead from shared/cc-snapshots/*.md (the
// append-only side) was the other candidate and is NOT possible here: those are
// raw CHANGELOG markdown with no gap_score or affected_skills, which come from
// the analysis step that writes the queue.
const queueWaves = gaps.map((w) => ({
  version: w.version,
  features: w.features.map((f) => ({
    slug: f.feature_slug,
    category: f.category,
    description: f.description,
    gapScore: f.gap_score,
    affectedSkills: f.affected_skills ?? [],
  })),
}));

/**
 * Waves already published in the committed board. Parsed from our own generated
 * file, which is emitted as `JSON.stringify(..., null, 2)` and therefore round
 * trips. A missing or unparseable file is not fatal: a fresh clone or a
 * hand-mangled artifact falls back to queue-only, which is the old behaviour.
 */
function readPublishedWaves() {
  const file = path.join(GEN, "cc-adoption-data.ts");
  // A genuinely absent file is the only silent fallback: a fresh clone has no
  // board yet and queue-only is correct there.
  if (!fs.existsSync(file)) return [];
  const text = fs.readFileSync(file, "utf8");

  // Scan from AFTER the marker, not from its start. The marker itself ends in
  // `AdoptionWave[] = `, so an indexOf("[", start) matches the bracket in the
  // TYPE ANNOTATION and slices from `[] = [` onward. That parses as a syntax
  // error, and with a silent catch it degraded to "no published waves" and
  // republished the truncated board this function exists to prevent, while
  // printing a perfectly plausible "0 carried forward".
  const MARKER = "export const ADOPTION_WAVES: AdoptionWave[] = ";
  const start = text.indexOf(MARKER);
  const open = start === -1 ? -1 : text.indexOf("[", start + MARKER.length);
  const close = open === -1 ? -1 : text.indexOf("\n];", open);

  // Anything else is LOUD. Falling back quietly here restores the exact data
  // loss this merge prevents, so it must never be a shrug.
  if (open === -1 || close === -1) {
    throw new Error(
      `[generate-lab-data] cannot locate ADOPTION_WAVES in ${file}. Refusing to ` +
        `regenerate, because replacing it would drop every published wave. Fix the ` +
        `file or delete it deliberately to rebuild from the queue alone.`,
    );
  }
  try {
    return JSON.parse(text.slice(open, close + 2));
  } catch (err) {
    throw new Error(
      `[generate-lab-data] ADOPTION_WAVES in ${file} did not parse as JSON ` +
        `(${err.message}). Refusing to regenerate; see above.`,
    );
  }
}

const waves = mergeWaves(readPublishedWaves(), queueWaves);

const carriedForward = waves.length - queueWaves.length;

const adoptionTs = `// Generated by docs/site/scripts/generate-lab-data.mjs — do not edit by hand.
// Sources: shared/cc-adoption-gaps.json + shared/cc-support.json

export interface AdoptionFeature {
  slug: string;
  category: string;
  description: string;
  gapScore: number;
  affectedSkills: string[];
}

export interface AdoptionWave {
  version: string;
  features: AdoptionFeature[];
}

export const ADOPTION_WAVES: AdoptionWave[] = ${JSON.stringify(waves, null, 2)};

export const CC_SUPPORT = {
  latest: "${esc(support.latest)}",
  latestKnown: "${esc(support.latest_known)}",
  supportedFloor: "${esc(support.supported_floor)}",
  policy: "${esc(support.policy)}",
} as const;

/** sha256 (first 12 hex) of the two source files above, in that order. */
export const SOURCE_DIGEST = "${sourceDigest}" as const;
`;
fs.writeFileSync(path.join(GEN, "cc-adoption-data.ts"), adoptionTs);

console.log(
  `[generate-lab-data] ${entries.length} lab entries → public/lab/ + lab-data.ts · ` +
    `${waves.length} adoption wave(s) → cc-adoption-data.ts ` +
    `(${queueWaves.length} from the queue, ${carriedForward} carried forward, source ${sourceDigest})`,
);
