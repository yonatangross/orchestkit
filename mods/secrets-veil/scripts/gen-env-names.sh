#!/usr/bin/env bash
# Generate src/env-names.ts from .env.tpl op:// lines.
#
# Extracts VAR names only (the left-hand side of op:// lines), never values.
# Output is a TypeScript const tuple that hooks/register.ts reads, because the
# CC plugin validate contract requires every $.env.get call site to carry a
# string LITERAL: a name read from JSON at runtime both fails the validate
# contract and cannot be listed statically.
#
# The first cut of this script defaulted ENV_TPL to a platform-checkout path
# and, when the file was absent, silently wrote an empty list. That empty list
# shipped a mod that masked nothing while looking like it worked. The script
# now fails loud instead: no template, or zero op:// names, is an error.
#
# Usage:
#   ENV_TPL=/path/to/platform/.env.tpl bash scripts/gen-env-names.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_FILE="${SCRIPT_DIR}/../src/env-names.ts"

ENV_TPL="${ENV_TPL:?set ENV_TPL to the platform .env.tpl path; refusing to guess}"

if [ ! -f "$ENV_TPL" ]; then
  echo "FAIL: ENV_TPL not found: $ENV_TPL" >&2
  exit 1
fi

# Extract VAR names from op:// lines. Format: VAR="op://..." or VAR='op://...'
# We only capture the VAR name, never the value.
set +e
NAMES=$(grep -E '^([A-Z_][A-Z0-9_]*)=["'\'']op://' "$ENV_TPL" | sed 's/^\([A-Z_][A-Z0-9_]*\)=.*/\1/' | sort -u)
RC=$?
set -e
if [ "$RC" -ne 0 ] || [ -z "$NAMES" ]; then
  echo "FAIL: $ENV_TPL has no op:// lines; not writing an empty name list" >&2
  exit 1
fi

COUNT=$(printf '%s\n' "$NAMES" | wc -l | tr -d ' ')

{
  echo "// secrets-veil: env-names.ts - literal env var names the mod reads"
  echo "// Generated by scripts/gen-env-names.sh from the platform .env.tpl"
  echo "// op:// lines. Names only, never values. Do not hand-edit: regenerate."
  echo "//"
  echo "// Every name here also appears as a literal \$.env.get call site in"
  echo "// hooks/register.ts, which is what the plugin validate contract reads."
  echo "export const KNOWN_ENV_NAMES = ["
  printf '%s\n' "$NAMES" | sed 's/^\(.*\)$/  "\1",/'
  echo "] as const;"
} > "$OUT_FILE"

echo "Generated $OUT_FILE with $COUNT names from $ENV_TPL"
echo "Now regenerate the \$.env.get call block in hooks/register.ts to match."
