/**
 * Consumer file content must pass through without plugin provenance headers.
 */

import { describe, it, expect, vi } from 'vitest';
import { mockCommonBasic } from '../fixtures/mock-common.js';

vi.mock('../../lib/common.js', () => mockCommonBasic());

import { writeHeaders } from '../../pretool/input-mod/write-headers.js';
import type { HookInput } from '../../types.js';
import { createTestContext } from '../fixtures/test-context.js';

describe('write-headers', () => {
  it.each([
    ['.github/workflows/deploy.yml', 'name: Deploy\non: push\n'],
    ['.github/workflows/deploy.yaml', 'name: Deploy\non: push\n'],
    ['.github/ISSUE_TEMPLATE/bug.yml', 'name: Bug report\n'],
    ['src/module.py', 'def main():\n    pass\n'],
    ['src/app.js', 'export const app = {};\n'],
    ['src/app.ts', 'export const app = {};\n'],
    ['src/app.TS', 'export const app = {};\n'],
    ['scripts/run.sh', 'echo hello\n'],
    ['scripts/run-with-shebang.sh', '#!/bin/sh\necho hello\n'],
    ['db/schema.sql', 'SELECT 1;\n'],
    ['index.html', '<html></html>\n'],
    ['config.xml', '<config />\n'],
    ['styles/main.css', 'body {}\n'],
    ['styles/main.scss', 'body {}\n'],
    ['styles/main.sass', 'body\n  color: red\n'],
    ['config/settings.json', '{"key":"value"}\n'],
    ['README.md', '# Project\n'],
    ['src/attributed.ts', '// Generated by OrchestKit Claude Plugin\nconst x = 1;\n'],
  ])('preserves new consumer file %s without updatedInput', (filePath, content) => {
    const input: HookInput = {
      tool_name: 'Write',
      session_id: 'test-session-4403',
      project_dir: '/test/consumer',
      tool_input: { file_path: `/test/consumer/${filePath}`, content },
    };
    const originalInput = structuredClone(input);

    const result = writeHeaders(input, createTestContext());

    expect(result.continue).toBe(true);
    expect(result.suppressOutput).toBe(true);
    expect(result.hookSpecificOutput).toBeUndefined();
    expect(input).toEqual(originalInput);
  });

  it('preserves Edit input without adding headers', () => {
    const input: HookInput = {
      tool_name: 'Edit',
      session_id: 'test-session-4403',
      project_dir: '/test/consumer',
      tool_input: { file_path: 'src/app.ts', old_string: 'a', new_string: 'b' },
    };
    const originalInput = structuredClone(input);

    const result = writeHeaders(input);

    expect(result.continue).toBe(true);
    expect(result.suppressOutput).toBe(true);
    expect(result.hookSpecificOutput).toBeUndefined();
    expect(input).toEqual(originalInput);
  });
});
